import { chromium } from 'playwright-core'; import { resolve } from 'node:path';
const S = process.env.S, base = 'file://' + resolve('dist/index.html') + '?today=2026-10-18';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 1500, height: 1000 }, acceptDownloads: true }); await ctx.addInitScript(() => localStorage.setItem('pl-digest-seen', 'off'));
const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(base + '#/project/jp3220'); await p.waitForSelector('.ph-title');
await p.click('.ph-actions button:has-text("Import report")');
await p.setInputFiles('.drawer input[type=file]', S + '/tpl/forecast.xlsx'); await p.waitForTimeout(2500);
await p.click('.drawer-f .btn.primary'); await p.waitForTimeout(800);
await p.click('.tabs button:has-text("Finance")'); await p.waitForTimeout(200); await p.click('.subtabs button:has-text("Forecast")'); await p.waitForTimeout(500);
await p.click('button:has-text("Fill staff")'); await p.waitForTimeout(500);
console.log('notes:', await p.locator('.fe-notes li').allInnerTexts());
const inp = p.locator('tr:has(td:has-text("5.7")) input.fe-in').first(); await inp.fill('10'); await inp.press('Tab'); await p.waitForTimeout(300);
console.log('decision:', (await p.locator('.fe-decision').innerText()).replace(/\n/g, ' | '));
await p.click('button:has-text("Balance on 5.7")'); await p.waitForTimeout(400);
console.log('after balance:', (await p.locator('.fe-decision').innerText()).replace(/\n/g, ' | '));
await p.screenshot({ path: S + '/fe.png', fullPage: false });
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('button:has-text("Excel for the project team")')]);
await dl.saveAs(S + '/fe.xlsx'); console.log('xlsx', dl.suggestedFilename(), 'errors', errs);
await b.close();
