"""Embed assets/*.webp as data URIs into src/assets.generated.js (keeps the guide a single offline file)."""
import base64, glob, json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
imgs = {os.path.splitext(os.path.basename(p))[0]: "data:image/webp;base64," + base64.b64encode(open(p, "rb").read()).decode() for p in sorted(glob.glob(os.path.join(root, "assets", "*.webp")))}
open(os.path.join(root, "src", "assets.generated.js"), "w").write("/* Generated by scripts/embed-assets.py — do not edit. */\nwindow.FG_IMG = " + json.dumps(imgs) + ";\n")
print("embedded", len(imgs))
