#!/usr/bin/env node
/* Extract the knowledge content of the uploaded v14 guide into a clean data module.
   Only literal data is taken; none of the v14 rendering code is carried over. */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const crypto = require("node:crypto");

const root = path.resolve(__dirname, "../..");
const source = path.join(root, "src/original/financial-guide/command-center-v14.html");
const EXPECTED = "e7623f88b34d7a0a51383ce3c6293b804a37217b6b00741917a6eaf606b6831f";
const html = fs.readFileSync(source);
if (crypto.createHash("sha256").update(html).digest("hex") !== EXPECTED) throw new Error("v14 baseline changed");
const text = html.toString("utf8");

// v14 variable name -> [new key, which occurrence (0-based) when the name is reused]
const WANTED = {
  phases: ["procurementStages", 0], checklists: ["procurementChecklists", 0], bestFor: ["procurementBestPractice", 0],
  procRoleDirectory: ["procurementRoles", 0], tenderDesignStages: ["tenderDesign", 0], thresholdRouteGuides: ["thresholdRoutes", 0],
  d: ["contractTypes", null], grantPhases: ["grantStages", 0], grantChecks: ["grantChecklists", 0], grantDetailNotes: ["grantNotes", 0],
  grantBestPractice: ["grantBestPractice", 0], m: ["grantCostCategories", null],
  poSteps: ["poSteps", 0], poServiceData: ["poServices", 0], poBestPairs: ["poBestPractice", 0],
  paySteps: ["paySteps", 0], payServiceData: ["payServices", 0], payBestPairs: ["payBestPractice", 0],
  eoyPhases: ["eoyPhases", 0], eoyPhaseMeta: ["eoyPhaseMeta", 0], eoyChecklist: ["eoyChecklist", 0], auditItems: ["auditItems", 0],
  fomaPoStages: ["fomaPoStages", 0], fomaPaymentStages: ["fomaPaymentStages", 0], fomaAdvancedData: ["fomaFlows", 0],
  forecastProcessData: ["forecastProcess", 0], forecastTriggerData: ["forecastTriggers", 0], fcBasicData: ["financeConcepts", 0],
  financialLifecycleData: ["financeLifecycle", 0], financialReportIntroData: ["reportIntro", 0],
  financialReportProcessData: ["reportProcess", 0], checks: ["reportChecks", 0],
  addendumReasonData: ["addendumReasons", 0], addendumStepData: ["addendumSteps", 0], docsByStage: ["addendumDocs", 0], keyByStage: ["addendumKeys", 0],
  v30ScenarioData: ["scenarios", 0], v30Contexts: ["moduleContexts", 0], usefulLinks: ["usefulLinks", 0], filingV29Data: ["filingMap", 0],
  financialAliases: ["columnAliases", 0], faCountryCatalogue: ["countries", 0],
};

function literalAt(i) {
  let depth = 0, quote = null;
  for (let j = i; j < text.length; j++) {
    const ch = text[j];
    if (quote) { if (ch === "\\") j++; else if (ch === quote) quote = null; continue; }
    if (ch === '"' || ch === "'" || ch === "`") quote = ch;
    else if (ch === "[" || ch === "{") depth++;
    else if (ch === "]" || ch === "}") { if (--depth === 0) return text.slice(i, j + 1); }
  }
  throw new Error("Unterminated literal at " + i);
}

const seen = {}, out = {};
const re = /(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*([\[{])/g;
for (let m; (m = re.exec(text));) {
  const name = m[1];
  if (!(name in WANTED)) continue;
  const index = seen[name] = (seen[name] ?? -1) + 1;
  const [key, wanted] = WANTED[name];
  if (key in out) continue;
  let value;
  try { value = vm.runInNewContext("(" + literalAt(m.index + m[0].length - 1) + ")", {}, { timeout: 500 }); } catch { continue; }
  // Short names (d, m) are reused for unrelated objects; pick the one with the expected shape.
  if (wanted === null) {
    if (key === "contractTypes" && !(value && value.one && value.fc && value.fa)) continue;
    if (key === "grantCostCategories" && !(value && value.staff && value.indirect)) continue;
  } else if (index !== wanted) continue;
  out[key] = value;
}
const missing = Object.values(WANTED).map(x => x[0]).filter(k => !(k in out));
if (missing.length) throw new Error("Missing content: " + missing.join(", "));
const target = path.join(root, "financial-guide/src/content.generated.js");
fs.writeFileSync(target, "/* Generated by scripts/extract-content.cjs from the v14 upload. Do not edit by hand. */\n" +
  "window.FG_CONTENT = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`Extracted ${Object.keys(out).length} datasets → ${path.relative(root, target)} (${fs.statSync(target).size.toLocaleString()} bytes)`);
